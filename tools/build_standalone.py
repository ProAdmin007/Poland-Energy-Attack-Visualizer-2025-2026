"""Build a single, self-contained HTML file of the app (no server needed).

Inlines styles.css, D3 (static/vendor) and app.js into index.html and embeds
the API responses, taken from the real FastAPI app so the data is identical
to what the server returns. The result opens straight from disk (file://)
and works offline; "PDF p. N" links go to the official PDFs on cert.pl.

Usage:
  python tools/build_standalone.py           # write Poland-Energy-Attack-Visualizer.html
  python tools/build_standalone.py --check   # exit 1 if that file is out of date
Needs:  pip install -r requirements-dev.txt
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
STATIC = BASE_DIR / "static"
OUT_FILE = BASE_DIR / "Poland-Energy-Attack-Visualizer.html"
D3_FILE = STATIC / "vendor" / "d3.v7.9.0.min.js"
D3_LICENSE = STATIC / "vendor" / "D3-LICENSE.txt"
API_PATHS = ["/api/metadata", "/api/incidents", "/api/timeline", "/api/attack-paths", "/api/summary"]


def api_responses() -> dict:
    sys.path.insert(0, str(BASE_DIR))
    from fastapi.testclient import TestClient  # noqa: E402
    import app  # noqa: E402

    with TestClient(app.app) as client:  # runs startup validation too
        out = {}
        for path in API_PATHS:
            r = client.get(path)
            r.raise_for_status()
            out[path] = r.json()
        return out


def replace_once(html: str, pattern: str, repl: str, what: str) -> str:
    new, n = re.subn(pattern, lambda _: repl, html, flags=re.S)
    if n != 1:
        raise SystemExit(f"build_standalone: expected exactly one {what} in index.html, found {n}")
    return new


def build() -> str:
    html = (STATIC / "index.html").read_text(encoding="utf-8")
    css = (STATIC / "styles.css").read_text(encoding="utf-8")
    js = (STATIC / "app.js").read_text(encoding="utf-8")
    d3 = D3_FILE.read_text(encoding="utf-8")
    license_text = D3_LICENSE.read_text(encoding="utf-8").strip()

    for name, text, tag in (("styles.css", css, "</style"), ("app.js", js, "</script"), ("d3", d3, "</script")):
        if tag in text.lower():
            raise SystemExit(f"build_standalone: {name} contains '{tag}', cannot inline safely")

    # "</" inside the JSON would end the <script> element early.
    data = json.dumps(api_responses(), ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")

    html = replace_once(html, r'<link rel="stylesheet" href="/static/styles\.css\?v=__ASSET_VERSION__" />',
                        f"<style>\n{css}\n</style>", "stylesheet link")
    html = replace_once(html, r'<script src="https://cdnjs\.cloudflare\.com/ajax/libs/d3/[^"]+"[^>]*></script>',
                        f"<script>\n/*! D3 v7.9.0 | ISC License\n{license_text}\n*/\n{d3}\n</script>", "D3 script tag")
    html = replace_once(html, r'<script src="/static/app\.js\?v=__ASSET_VERSION__"></script>',
                        f"<script>window.__STANDALONE_DATA__ = {data};</script>\n<script>\n{js}\n</script>",
                        "app.js script tag")
    banner = ("<!-- Standalone build of Poland Energy Attack Visualizer. Generated by "
              "tools/build_standalone.py - do not edit by hand. -->\n")
    return banner + html


def main() -> int:
    html = build()
    if "--check" in sys.argv:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if current != html:
            print(f"{OUT_FILE.name} is out of date: run python tools/build_standalone.py")
            return 1
        print(f"{OUT_FILE.name} is up to date")
        return 0
    OUT_FILE.write_text(html, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_FILE.name} ({OUT_FILE.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
